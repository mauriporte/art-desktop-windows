const { contextBridge, ipcRenderer } = require('electron')

const lang = () => { try { return localStorage.getItem('lang') || 'es' } catch { return 'es' } }

contextBridge.exposeInMainWorld('art', {
  setOpen: (open) => ipcRenderer.send('notch:open', open),
  onOpened: (fn) => ipcRenderer.on('notch:opened', fn),
  panelPinned: (on) => ipcRenderer.send('panel:pinned', on),
  inside: () => ipcRenderer.invoke('notch:inside'),
  dockApps: () => ipcRenderer.invoke('dock:apps'),
  dockOrder: (names) => ipcRenderer.invoke('dock:order', names),
  launch: (lnk) => ipcRenderer.invoke('dock:launch', lnk),
  activate: (lnk) => ipcRenderer.invoke('dock:activate', lnk),
  appWindows: () => ipcRenderer.invoke('dock:windows'),
  runningApps: () => ipcRenderer.invoke('dock:running'),
  // the native menus are drawn in the page's language (i18n.js keeps it in storage as "lang", default ES)
  appMenu: (lnk) => ipcRenderer.send('dock:appMenu', lnk, lang()),
  widgetMenu: () => ipcRenderer.send('widget:menu', lang()),
  dockMenu: (stackName) => ipcRenderer.send('dock:menu', stackName, lang()),
  stack: (name) => ipcRenderer.invoke('dock:stack', name),
  openFile: (p) => ipcRenderer.invoke('dock:open', p),
  stacks: () => ipcRenderer.invoke('dock:stacks'),
  onDockChanged: (fn) => ipcRenderer.on('dock:changed', fn),
  showTray: () => ipcRenderer.invoke('tray:show'),
  getTaskbarHidden: () => ipcRenderer.invoke('taskbar:get'),
  setTaskbarHidden: (hide) => ipcRenderer.invoke('taskbar:set', hide),
  onTaskbar: (fn) => ipcRenderer.on('taskbar:changed', (_e, hidden) => fn(hidden)),
  onDockGap: (fn) => ipcRenderer.on('dock:gap', (_e, px) => fn(px)),
  dockExpand: (on) => ipcRenderer.send('dock:expand', on),
  getRadios: () => ipcRenderer.invoke('radios:get'),
  quick: () => ipcRenderer.invoke('quick:get'),
  setTraffic: (via, wifi, lan) => ipcRenderer.invoke('traffic:set', via, wifi, lan),
  setQuick: (op, value) => ipcRenderer.invoke('quick:set', op, value),
  weather: (city) => ipcRenderer.invoke('weather:get', city),
  haUrl: () => ipcRenderer.invoke('ha:url'),
  house: () => ipcRenderer.invoke('house:get'),
  claude: {
    state: () => ipcRenderer.invoke('claude:state'),
    decide: (id, allow) => ipcRenderer.invoke('claude:decide', id, allow),
    detail: (id) => ipcRenderer.invoke('claude:detail', id),
    reply: (session, text) => ipcRenderer.invoke('claude:reply', session, text),
    onChange: (fn) => { const h = () => fn(); ipcRenderer.on('claude:changed', h); return () => ipcRenderer.off('claude:changed', h) },
    onPending: (fn) => ipcRenderer.on('claude:pending', (_e, n) => fn(n)),
  },
  jarvis: {
    start: (text, dictate) => ipcRenderer.invoke('jarvis:start', text, dictate),
    audio: (chunk) => ipcRenderer.send('jarvis:audio', chunk),
    stop: () => ipcRenderer.send('jarvis:stop'),
    speech: (message) => ipcRenderer.invoke('jarvis:speech', message),
    onEvent: (fn) => { const h = (_e, ev) => fn(ev); ipcRenderer.on('jarvis:event', h); return () => ipcRenderer.off('jarvis:event', h) },
  },
  clip: {
    list: () => ipcRenderer.invoke('clip:list'),
    copy: (id) => ipcRenderer.invoke('clip:copy', id),
    remove: (id) => ipcRenderer.invoke('clip:remove', id),
    clear: () => ipcRenderer.invoke('clip:clear'),
    onChange: (fn) => { const h = () => fn(); ipcRenderer.on('clip:changed', h); return () => ipcRenderer.off('clip:changed', h) },
  },
  ideas: {
    list: () => ipcRenderer.invoke('ideas:list'),
    geo: () => ipcRenderer.invoke('ideas:geo'),
    open: (id) => ipcRenderer.invoke('ideas:open', id),
  },
  power: (what) => ipcRenderer.invoke('power:do', what),
  grab: {
    start: (how) => ipcRenderer.invoke('grab:start', how),
    ask: (image, question, model) => ipcRenderer.invoke('ask:run', image, question, model),
    stopAsk: () => ipcRenderer.send('ask:stop'),
    onAnswer: (fn) => { const h = (_e, piece) => fn(piece); ipcRenderer.on('ask:chunk', h); return () => ipcRenderer.off('ask:chunk', h) },
    data: () => ipcRenderer.invoke('grab:data'),
    pick: (r) => ipcRenderer.invoke('grab:pick', r),
    copy: (url) => ipcRenderer.invoke('grab:copy', url),
    save: (url) => ipcRenderer.invoke('grab:save', url),
    pin: (url) => ipcRenderer.invoke('grab:pin', url),
    close: () => ipcRenderer.send('grab:close'),
  },
  ha: (op, ...a) => ipcRenderer.invoke('ha:' + op, ...a),
  remote: (op, ...a) => ipcRenderer.invoke('remote:' + op, ...a),
  setRadio: (kind, on) => ipcRenderer.invoke('radios:set', kind, on),
})
